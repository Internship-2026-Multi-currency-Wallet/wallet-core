import { Inject, Injectable } from '@nestjs/common';
import type { Knex } from 'knex';
import { KNEX } from '../database/database.module.js';
import { isDeadlock } from '../database/deadlock.js';
import { isUniqueViolation } from '../database/unique-violation.js';
import { StaffRole } from './permissions.js';
import { StaffStatus } from './staff.model.js';

const STAFF = 'staff';
const EMAIL_UNIQUE = 'staff_email_unique';
const INVITATIONS = 'staff_invitations';
const SESSIONS = 'staff_sessions';
const MAX_TRANSACTION_ATTEMPTS = 3;

export interface NewInvitation {
  id: string;
  staffId: string;
  /** SHA-256 hex of the token in the link. */
  tokenHash: string;
  expiresAt: Date;
  createdAt: Date;
}

export interface NewStaffSession {
  id: string;
  staffId: string;
  /** SHA-256 hex of the refresh token cookie. */
  refreshTokenHash: string;
  expiresAt: Date;
  createdAt: Date;
}

export interface LoginLockPolicy {
  now: Date;
  maxFailedAttempts: number;
  lockDurationMs: number;
}

export interface NewStaff {
  /** UUID generated by the app. */
  id: string;
  /** Already trimmed and lower-cased. */
  email: string;
  role: StaffRole;
  createdAt: Date;
}

export interface StaffRecord {
  id: string;
  email: string;
  role: StaffRole;
  status: StaffStatus;
  /** Null while invited. */
  passwordHash: string | null;
  failedLoginAttempts: number;
  lockedUntil: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

export const InsertStaffResult = {
  Created: 'created',
  EmailTaken: 'emailTaken',
} as const;

export type InsertStaffResult = (typeof InsertStaffResult)[keyof typeof InsertStaffResult];

interface StaffRow {
  id: string;
  email: string;
  role: StaffRole;
  status: StaffStatus;
  password_hash: string | null;
  failed_login_attempts: number;
  locked_until: Date | null;
  created_at: Date;
  updated_at: Date;
}

class RotationRejected extends Error {}

interface StaffSessionRow {
  id: string;
  staff_id: string;
  refresh_token_hash: string;
  expires_at: Date;
  revoked_at: Date | null;
}

@Injectable()
export class StaffRepository {
  constructor(@Inject(KNEX) private readonly db: Knex) {}

  async insert(staff: NewStaff): Promise<InsertStaffResult> {
    try {
      await this.db(STAFF).insert({
        id: staff.id,
        email: staff.email,
        role: staff.role,
        status: StaffStatus.INVITED,
        created_at: staff.createdAt,
        updated_at: staff.createdAt,
      });
      return InsertStaffResult.Created;
    } catch (error) {
      if (isUniqueViolation(error, EMAIL_UNIQUE)) return InsertStaffResult.EmailTaken;
      throw error;
    }
  }

  async transaction<T>(work: (tx: StaffRepository) => Promise<T>): Promise<T> {
    // InnoDB gap locks can deadlock concurrent promotions and resends; a new attempt is safe.
    for (let attempt = 1; ; attempt += 1) {
      try {
        return await this.db.transaction((trx) => work(new StaffRepository(trx)));
      } catch (error) {
        if (attempt >= MAX_TRANSACTION_ATTEMPTS || !isDeadlock(error)) throw error;
      }
    }
  }

  /**
   * Every role or status change locks the active admins first, then its target, so these changes
   * can't remove the last admin; a deadlock between them is retried in `transaction`.
   */
  async lockActiveAdminIds(): Promise<string[]> {
    return (await this.db(STAFF)
      .where({ role: StaffRole.ADMIN, status: StaffStatus.ACTIVE })
      .orderBy('id')
      .forUpdate()
      .pluck('id')) as string[];
  }

  /** Call inside `transaction`: every admin, in any status, so a concurrent first-admin insert waits. */
  async lockAdminIds(): Promise<string[]> {
    return (await this.db(STAFF)
      .where({ role: StaffRole.ADMIN })
      .orderBy('id')
      .forUpdate()
      .pluck('id')) as string[];
  }

  async update(
    id: string,
    patch: { role?: StaffRole; status?: StaffStatus },
    at: Date,
  ): Promise<void> {
    await this.db(STAFF)
      .where({ id })
      .update({ ...patch, updated_at: at });
  }

  async findById(id: string): Promise<StaffRecord | undefined> {
    const row = (await this.db(STAFF).where({ id }).first()) as StaffRow | undefined;
    return row && toRecord(row);
  }

  /** `findById` with `FOR UPDATE`: call inside `transaction`; the row stays locked until it ends. */
  async lockById(id: string): Promise<StaffRecord | undefined> {
    const row = (await this.db(STAFF).where({ id }).forUpdate().first()) as StaffRow | undefined;
    return row && toRecord(row);
  }

  /** Case-insensitive: the column uses the default (case-insensitive) collation. */
  async findByEmail(email: string): Promise<StaffRecord | undefined> {
    const row = (await this.db(STAFF).where({ email }).first()) as StaffRow | undefined;
    return row && toRecord(row);
  }

  async list(): Promise<StaffRecord[]> {
    const rows = (await this.db(STAFF).orderBy([
      { column: 'created_at', order: 'asc' },
      { column: 'id', order: 'asc' },
    ])) as StaffRow[];
    return rows.map(toRecord);
  }

  /** Any admin in any status, including invited (bootstrap must not invite a second one). */
  async anyAdminExists(): Promise<boolean> {
    return (await this.db(STAFF).where({ role: StaffRole.ADMIN }).first('id')) !== undefined;
  }

  async revokeSessions(
    staffId: string,
    at: Date,
    options: { except?: string } = {},
  ): Promise<void> {
    await this.db(SESSIONS)
      .where({ staff_id: staffId })
      .whereNull('revoked_at')
      .modify((q) => {
        if (options.except !== undefined) void q.whereNot({ id: options.except });
      })
      .update({ revoked_at: at });
  }

  async createSession(session: NewStaffSession): Promise<void> {
    await this.db(SESSIONS).insert({
      id: session.id,
      staff_id: session.staffId,
      refresh_token_hash: session.refreshTokenHash,
      expires_at: session.expiresAt,
      created_at: session.createdAt,
    });
  }

  async revokeSessionByHash(refreshTokenHash: string, at: Date): Promise<void> {
    await this.db(SESSIONS)
      .where({ refresh_token_hash: refreshTokenHash })
      .whereNull('revoked_at')
      .update({ revoked_at: at });
  }

  /** Reads staff without a lock, to keep the staff-then-session lock order of deactivation and role changes. */
  async rotateSession(
    refreshTokenHash: string,
    newRefreshTokenHash: string,
    now: Date,
  ): Promise<{ staff: StaffRecord; expiresAt: Date } | null> {
    try {
      return await this.transaction(async (tx) => {
        const updated = await tx
          .db(SESSIONS)
          .where({ refresh_token_hash: refreshTokenHash })
          .whereNull('revoked_at')
          .andWhere('expires_at', '>', now)
          .update({ refresh_token_hash: newRefreshTokenHash });
        if (updated === 0) throw new RotationRejected();
        const session = await tx
          .db<StaffSessionRow>(SESSIONS)
          .where({ refresh_token_hash: newRefreshTokenHash })
          .first('staff_id', 'expires_at');
        if (!session) throw new RotationRejected();
        const staff = await tx.findById(session.staff_id);
        // Throwing rolls the rotation back.
        if (staff?.status !== StaffStatus.ACTIVE) throw new RotationRejected();
        return { staff, expiresAt: session.expires_at };
      });
    } catch (error) {
      if (error instanceof RotationRejected) return null;
      throw error;
    }
  }

  async resetFailedLogins(id: string, at: Date): Promise<void> {
    await this.db(STAFF)
      .where({ id })
      .update({ failed_login_attempts: 0, locked_until: null, updated_at: at });
  }

  // Serialize failed-attempt updates on the staff row so concurrent guesses cannot bypass the
  // lockout threshold.
  async recordFailedLogin(id: string, policy: LoginLockPolicy): Promise<Date | null> {
    return this.transaction(async (tx) => {
      const row = await tx.lockById(id);
      if (!row) return null;
      if (row.lockedUntil && row.lockedUntil > policy.now) return row.lockedUntil;

      const attempts = row.failedLoginAttempts + 1;
      const lockUntil =
        attempts >= policy.maxFailedAttempts
          ? new Date(policy.now.getTime() + policy.lockDurationMs)
          : null;
      await tx
        .db(STAFF)
        .where({ id })
        .update({
          failed_login_attempts: lockUntil ? 0 : attempts,
          locked_until: lockUntil,
          updated_at: policy.now,
        });
      return lockUntil;
    });
  }

  async insertInvitation(invitation: NewInvitation): Promise<void> {
    await this.db(INVITATIONS).insert({
      id: invitation.id,
      staff_id: invitation.staffId,
      token_hash: invitation.tokenHash,
      expires_at: invitation.expiresAt,
      created_at: invitation.createdAt,
    });
  }

  async findInvitationStaffId(tokenHash: string, now: Date): Promise<string | undefined> {
    // Rejects dead tokens before argon2 and the admin locks; consumeInvitation under the locks stays authoritative.
    const row = (await this.db(INVITATIONS)
      .select('staff_id')
      .where({ token_hash: tokenHash })
      .whereNull('used_at')
      .where('expires_at', '>', now)
      .first()) as { staff_id: string } | undefined;
    return row?.staff_id;
  }

  async activate(id: string, passwordHash: string, at: Date): Promise<void> {
    await this.db(STAFF).where({ id }).update({
      status: StaffStatus.ACTIVE,
      password_hash: passwordHash,
      failed_login_attempts: 0,
      locked_until: null,
      updated_at: at,
    });
  }

  async expireInvitations(staffId: string, at: Date): Promise<void> {
    await this.db(INVITATIONS)
      .where({ staff_id: staffId })
      .whereNull('used_at')
      .where('expires_at', '>', at)
      .update({ expires_at: at });
  }

  /** A conditional UPDATE prevents concurrent accepts from consuming the same invitation. */
  async consumeInvitation(tokenHash: string, at: Date): Promise<string | null> {
    const updated = await this.db(INVITATIONS)
      .where({ token_hash: tokenHash })
      .whereNull('used_at')
      .where('expires_at', '>', at)
      .update({ used_at: at });
    if (updated === 0) return null;
    const row = (await this.db(INVITATIONS)
      .select('staff_id')
      .where({ token_hash: tokenHash })
      .first()) as { staff_id: string };
    return row.staff_id;
  }
}

function toRecord(row: StaffRow): StaffRecord {
  return {
    id: row.id,
    email: row.email,
    role: row.role,
    status: row.status,
    passwordHash: row.password_hash,
    failedLoginAttempts: row.failed_login_attempts,
    lockedUntil: row.locked_until,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  };
}
