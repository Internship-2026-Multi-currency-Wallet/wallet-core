import { Inject, Injectable } from '@nestjs/common';
import type { Knex } from 'knex';
import { KNEX } from '../database/database.module.js';
import { isUniqueViolation } from '../database/unique-violation.js';
import { StaffRole } from './permissions.js';
import { StaffStatus } from './staff.model.js';

const STAFF = 'staff';
const EMAIL_UNIQUE = 'staff_email_unique';
const INVITATIONS = 'staff_invitations';
const SESSIONS = 'staff_sessions';

export interface NewInvitation {
  id: string;
  staffId: string;
  /** SHA-256 hex of the token in the link. */
  tokenHash: string;
  expiresAt: Date;
  createdAt: Date;
}

export interface NewStaff {
  /** UUID generated by the app. */
  id: string;
  /** Already trimmed and lower-cased. */
  email: string;
  role: StaffRole;
  createdAt: Date;
}

export interface StaffRecord {
  id: string;
  email: string;
  role: StaffRole;
  status: StaffStatus;
  /** Null while invited. */
  passwordHash: string | null;
  failedLoginAttempts: number;
  lockedUntil: Date | null;
  createdAt: Date;
  updatedAt: Date;
}

export const InsertStaffResult = {
  Created: 'created',
  EmailTaken: 'emailTaken',
} as const;

export type InsertStaffResult = (typeof InsertStaffResult)[keyof typeof InsertStaffResult];

interface StaffRow {
  id: string;
  email: string;
  role: StaffRole;
  status: StaffStatus;
  password_hash: string | null;
  failed_login_attempts: number;
  locked_until: Date | null;
  created_at: Date;
  updated_at: Date;
}

@Injectable()
export class StaffRepository {
  constructor(@Inject(KNEX) private readonly db: Knex) {}

  /** A new staff member is always invited: the password is set when the invitation is accepted. */
  async insert(staff: NewStaff): Promise<InsertStaffResult> {
    try {
      await this.db(STAFF).insert({
        id: staff.id,
        email: staff.email,
        role: staff.role,
        status: StaffStatus.INVITED,
        created_at: staff.createdAt,
        updated_at: staff.createdAt,
      });
      return InsertStaffResult.Created;
    } catch (error) {
      if (isUniqueViolation(error, EMAIL_UNIQUE)) return InsertStaffResult.EmailTaken;
      throw error;
    }
  }

  /**
   * Runs `work` in one database transaction with a repository bound to it; rolls back if it throws.
   * Used for the last-admin rule: lock the active admins, check, then change.
   */
  async transaction<T>(work: (tx: StaffRepository) => Promise<T>): Promise<T> {
    return this.db.transaction((trx) => work(new StaffRepository(trx)));
  }

  /**
   * Ids of the ACTIVE admins, locked (`FOR UPDATE`) until the transaction ends. Every role or status
   * change locks the active admins first, then its target, so these changes serialize and can't
   * remove the last admin. Call inside `transaction`.
   */
  async lockActiveAdminIds(): Promise<string[]> {
    return (await this.db(STAFF)
      .where({ role: StaffRole.ADMIN, status: StaffStatus.ACTIVE })
      .orderBy('id')
      .forUpdate()
      .pluck('id')) as string[];
  }

  async update(
    id: string,
    patch: { role?: StaffRole; status?: StaffStatus },
    at: Date,
  ): Promise<void> {
    await this.db(STAFF)
      .where({ id })
      .update({ ...patch, updated_at: at });
  }

  async findById(id: string): Promise<StaffRecord | undefined> {
    const row = (await this.db(STAFF).where({ id }).first()) as StaffRow | undefined;
    return row && toRecord(row);
  }

  /** `findById` with `FOR UPDATE`: call inside `transaction`; the row stays locked until it ends. */
  async lockById(id: string): Promise<StaffRecord | undefined> {
    const row = (await this.db(STAFF).where({ id }).forUpdate().first()) as StaffRow | undefined;
    return row && toRecord(row);
  }

  /** Case-insensitive: the column uses the default (case-insensitive) collation. */
  async findByEmail(email: string): Promise<StaffRecord | undefined> {
    const row = (await this.db(STAFF).where({ email }).first()) as StaffRow | undefined;
    return row && toRecord(row);
  }

  async list(): Promise<StaffRecord[]> {
    const rows = (await this.db(STAFF).orderBy([
      { column: 'created_at', order: 'asc' },
      { column: 'id', order: 'asc' },
    ])) as StaffRow[];
    return rows.map(toRecord);
  }

  /** Any admin in any status, including invited (bootstrap must not invite a second one). */
  async anyAdminExists(): Promise<boolean> {
    return (await this.db(STAFF).where({ role: StaffRole.ADMIN }).first('id')) !== undefined;
  }

  /**
   * Ends the staff member's active sessions (role change, deactivation, password change). With
   * `except`, that session (the caller's own) stays active.
   */
  async revokeSessions(
    staffId: string,
    at: Date,
    options: { except?: string } = {},
  ): Promise<void> {
    await this.db(SESSIONS)
      .where({ staff_id: staffId })
      .whereNull('revoked_at')
      .modify((q) => {
        if (options.except !== undefined) void q.whereNot({ id: options.except });
      })
      .update({ revoked_at: at });
  }

  async insertInvitation(invitation: NewInvitation): Promise<void> {
    await this.db(INVITATIONS).insert({
      id: invitation.id,
      staff_id: invitation.staffId,
      token_hash: invitation.tokenHash,
      expires_at: invitation.expiresAt,
      created_at: invitation.createdAt,
    });
  }

  /** Ends every unused, still valid invitation of the staff member at `at` (resend). */
  async expireInvitations(staffId: string, at: Date): Promise<void> {
    await this.db(INVITATIONS)
      .where({ staff_id: staffId })
      .whereNull('used_at')
      .where('expires_at', '>', at)
      .update({ expires_at: at });
  }

  /**
   * Marks the invitation used if it is unused and not expired at `at`; answers its staff id, or
   * `null` (unknown, used, expired or replaced). One UPDATE, so two concurrent accepts cannot both win.
   */
  async consumeInvitation(tokenHash: string, at: Date): Promise<string | null> {
    const updated = await this.db(INVITATIONS)
      .where({ token_hash: tokenHash })
      .whereNull('used_at')
      .where('expires_at', '>', at)
      .update({ used_at: at });
    if (updated === 0) return null;
    const row = (await this.db(INVITATIONS)
      .select('staff_id')
      .where({ token_hash: tokenHash })
      .first()) as { staff_id: string };
    return row.staff_id;
  }
}

function toRecord(row: StaffRow): StaffRecord {
  return {
    id: row.id,
    email: row.email,
    role: row.role,
    status: row.status,
    passwordHash: row.password_hash,
    failedLoginAttempts: row.failed_login_attempts,
    lockedUntil: row.locked_until,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
  };
}
